#!/usr/bin/env julia
"""
DiffDose neutropenia timing analysis.

This experiment driver imports the translated model from
`utils/NeutropeniaDDEModel.jl`, optimizes one 300 microgram filgrastim administration
time in each of seven CHOP-14 cycles, and writes convergence, schedule, ANC,
and configuration outputs.

The timing controls use sharp sigmoid onset maps (`SIGMOID_EPS = 0.0005` day)
inside the DDE right-hand side. ForwardDiff therefore differentiates the
smoothed, discretized timing objective. This is distinct from the fixed-time
callback path exposed by the model module and from exact fixed-time amplitude
jumps in `IDR.py` and `utils/MosunModel.jl`.

Quick smoke test:

    julia +1.11.6 --project=environments/dde NeutropeniaDDE.jl --preset quick --output output

Manuscript configuration:

    julia +1.11.6 --project=environments/dde NeutropeniaDDE.jl --preset paper --methods all --output output

Scientific sources and DOI links are listed in
`utils/NeutropeniaDDEModel.jl`.
"""


include(joinpath(@__DIR__, "utils", "NeutropeniaDDEModel.jl"))
using .NeutropeniaDDEModel.Parameters
using .NeutropeniaDDEModel.Dosing
using .NeutropeniaDDEModel.SolverUndeclared

"""
7-Cycle CHOP-14 Benchmark  — G-CSF timing optimisation in 7 dimensions.

Decision variable: x ∈ ℝ⁷ — injection day within each cycle (relative to cycle start).
    Absolute injection time for cycle c (0-indexed) = c*14 + x[c+1].

Methods (same 6):
  1. AD + ADAM          (ForwardDiff gradient)
  2. AD + L-BFGS        (ForwardDiff gradient, box-constrained)
  3. FD + ADAM          (central-difference gradient, h = 1e-4)
  4. FD + L-BFGS        (Optim finite-diff L-BFGS, box-constrained)
  5. Nelder–Mead        (derivative-free simplex)
  6. Simulated Annealing (derivative-free stochastic)

All start from x₀ = [4, 4, 4, 4, 4, 4, 4]  (G-CSF on day 4 of each cycle).
Computational budget: 600 forward DDE solves.
  • AD+ADAM:  1 AD solve + 1 loss = 2 per iter  → 300 iters
  • FD+ADAM:  2×7 central diff + 1 loss = 15 per iter → 40 iters
  → ∼8× more gradient steps for AD, which is the central demonstration.

Outputs:
  • CSV  – per-method convergence history + summary table + ANC traces
  • JSON – full configuration
  • Figures generated by companion script `Figures/plot_Figure3.jl`
"""

using Printf, Statistics, Random, DifferentialEquations, Dates
import ForwardDiff
using Optim
using JSON3, CSV, DataFrames

# ── Constants ──────────────────────────────────────────────
const ANC_SCALE   = 8.19
const ANC_IDX     = 2
const CYCLE_LEN   = 14.0
const N_CYCLES    = 7
const T_END       = N_CYCLES * CYCLE_LEN   # 98 days
const CHEMO_W     = 1.0 / 24.0
const DOSE_AMT    = 300_000.0
const SIGMOID_EPS = 0.0005
const ANC_THR     = 2.0
const SAVEAT      = 0.05
const T_MIN       = 0.5          # earliest injection relative to cycle start
const T_MAX       = 13.0         # latest
const T_INIT      = 4.0          # initial condition per cycle
const FD_STEP     = 1e-4
const DIM         = N_CYCLES     # 7-dimensional problem


function parse_cli(args)
    options = Dict{String,String}(
        "preset" => "quick",
        "methods" => "diffdose",
        "output" => joinpath(@__DIR__, "output"),
    )
    index = 1
    while index <= length(args)
        flag = args[index]
        flag in ("--preset", "--methods", "--output") ||
            throw(ArgumentError("Unknown option: $flag"))
        index == length(args) && throw(ArgumentError("Missing value after $flag"))
        options[flag[3:end]] = args[index + 1]
        index += 2
    end
    options["preset"] in ("quick", "paper") ||
        throw(ArgumentError("--preset must be quick or paper"))
    options["methods"] in ("diffdose", "all") ||
        throw(ArgumentError("--methods must be diffdose or all"))
    return options
end

# ── Loss function (7-cycle) ───────────────────────────────
"""
    timing_loss_7c(x)

x is a 7-element vector: x[c] = G-CSF injection day relative to cycle c-1 start.
Loss = ∫₀⁹⁸ max(0, 2.0 − ANC(t)) dt  (trapezoidal).
"""
function timing_loss_7c(x::AbstractVector{D}) where D
    p = default_parameters(D)
    p.AdminChemo = 1; p.AdminGCSF = 1; p.DayAdminChemo = D(0.0)
    p.DeltaC = D(CHEMO_W); p.Period = D(CYCLE_LEN)
    p.NumAdminsChemo = N_CYCLES; p.DoseChemo = D(4000.0)
    p.TotalDose = D(4000.0) * p.BSA; p.Dose = D(DOSE_AMT)
    p.GCSFPeriod = D(1.0); p.AdminsGCSF = 1; p.AdminDay = D(8.0)
    recompute_derived!(p)

    tspan = (0.0, T_END)   # Float64 — tspan doesn't depend on x

    # Build chemo schedule: one infusion at the start of each cycle (Float64 times)
    cs = [ChemoInfusion(Float64(c * CYCLE_LEN), p.TotalDose, p.DeltaC) for c in 0:N_CYCLES-1]

    # Build G-CSF schedule: one injection per cycle at the optimised time (Dual via x)
    gs = [GCSFInjection(D(c * CYCLE_LEN) + x[c+1], D(DOSE_AMT)) for c in 0:N_CYCLES-1]

    sol = solve_scenario_undeclared(p, tspan;
        chemo_schedule=cs, gcsf_schedule=gs,
        smooth_chemo=true,  chemo_smooth_shape=:sigmoid, chemo_smooth_width=D(SIGMOID_EPS),
        smooth_gcsf=true,   gcsf_smooth_shape=:sigmoid,  gcsf_smooth_width=D(SIGMOID_EPS),
        reltol=1e-8, abstol=1e-8, dtmax=1e-2, saveat=SAVEAT)

    loss = zero(D); thr = D(ANC_THR)
    for i in 2:length(sol.t)
        dt = sol.t[i] - sol.t[i-1]
        a1 = D(ANC_SCALE) * sol.u[i-1][ANC_IDX]
        a2 = D(ANC_SCALE) * sol.u[i][ANC_IDX]
        loss += D(0.5) * (max(zero(D), thr - a1) + max(zero(D), thr - a2)) * dt
    end
    return loss
end

# Float64-only wrapper
timing_loss_7c_f64(x::Vector{Float64}) = timing_loss_7c(x)

# ── AD gradient (ForwardDiff, 7-dim) ──────────────────────
function ad_gradient_7c(x::Vector{Float64})
    return ForwardDiff.gradient(timing_loss_7c, x)
end

# ── FD gradient (central difference, 2×7 + 1 loss = 15 solves) ─
function fd_gradient_7c(x::Vector{Float64})
    g = zeros(DIM)
    for d in 1:DIM
        xp = copy(x); xp[d] += FD_STEP
        xm = copy(x); xm[d] -= FD_STEP
        g[d] = (timing_loss_7c_f64(xp) - timing_loss_7c_f64(xm)) / (2 * FD_STEP)
    end
    return g
end

# ── ADAM (vector) ─────────────────────────────────────────
function adam_step_vec!(θ, g, m, v, iter; lr=0.05, β1=0.9, β2=0.999, ε=1e-8)
    for d in 1:length(θ)
        m[d] = β1 * m[d] + (1 - β1) * g[d]
        v[d] = β2 * v[d] + (1 - β2) * g[d]^2
        m̂ = m[d] / (1 - β1^iter)
        v̂ = v[d] / (1 - β2^iter)
        θ[d] -= lr * m̂ / (sqrt(v̂) + ε)
        θ[d] = clamp(θ[d], T_MIN, T_MAX)
    end
end

# ── History record ─────────────────────────────────────────
struct MethodResult7C
    name::String
    best_x::Vector{Float64}      # 7-element optimised timing
    best_loss::Float64
    loss_history::Vector{Float64}
    time_history::Vector{Float64}
    solve_history::Vector{Int}
    total_solves::Int
    wall_time::Float64
end

struct BudgetExhausted <: Exception end

# =====================================================================
#  METHOD 1:  AD + ADAM  (2 solves / iter)
# =====================================================================
function run_ad_adam_7c(; budget, lr=0.05)
    θ = fill(T_INIT, DIM)
    m = zeros(DIM); v = zeros(DIM)
    best_loss = Inf; best_x = copy(θ)
    losses = Float64[]; times = Float64[]; solves = Int[]
    n_solve = 0; t0 = time()

    n_iters = budget ÷ 2
    for iter in 1:n_iters
        g = ad_gradient_7c(θ)               # 1 AD forward solve
        l = timing_loss_7c_f64(θ)           # 1 forward solve
        n_solve += 2
        if l < best_loss; best_loss = l; best_x = copy(θ); end
        push!(losses, best_loss); push!(times, time()-t0); push!(solves, n_solve)
        adam_step_vec!(θ, g, m, v, iter; lr=lr)
    end
    return MethodResult7C("AD+ADAM", best_x, best_loss, losses, times, solves,
                          n_solve, time()-t0)
end

# =====================================================================
#  METHOD 2:  AD + L-BFGS  (box-constrained, hard budget cap)
# =====================================================================
function run_ad_lbfgs_7c(; budget)
    n_solve = Ref(0)
    losses = Float64[]; tms = Float64[]; svs = Int[]
    best_loss = Ref(Inf); best_x = Ref(fill(T_INIT, DIM))
    t0 = time()

    function fg!(F, G, x)
        n_solve[] >= budget && throw(BudgetExhausted())
        xc = clamp.(x, T_MIN, T_MAX)
        l = timing_loss_7c_f64(xc); n_solve[] += 1
        if l < best_loss[]; best_loss[] = l; best_x[] = copy(xc); end
        push!(losses, best_loss[]); push!(tms, time()-t0); push!(svs, n_solve[])
        if G !== nothing
            n_solve[] >= budget && throw(BudgetExhausted())
            G .= ad_gradient_7c(xc); n_solve[] += 1
        end
        if F !== nothing; return l; end
    end

    try
        Optim.optimize(Optim.only_fg!(fg!),
                       fill(T_MIN, DIM), fill(T_MAX, DIM), fill(T_INIT, DIM),
                       Fminbox(LBFGS()),
                       Optim.Options(iterations=10_000, f_abstol=1e-14,
                                     g_tol=1e-12, allow_f_increases=true))
    catch e
        e isa BudgetExhausted || rethrow(e)
    end
    return MethodResult7C("AD+LBFGS", best_x[], best_loss[], losses, tms, svs,
                          n_solve[], time()-t0)
end

# =====================================================================
#  METHOD 3:  FD + ADAM  (2D+1 = 15 solves / iter)
# =====================================================================
function run_fd_adam_7c(; budget, lr=0.05)
    θ = fill(T_INIT, DIM)
    m = zeros(DIM); v = zeros(DIM)
    best_loss = Inf; best_x = copy(θ)
    losses = Float64[]; times = Float64[]; solves = Int[]
    n_solve = 0; t0 = time()

    solves_per_iter = 2 * DIM + 1   # 15
    n_iters = budget ÷ solves_per_iter
    for iter in 1:n_iters
        g = fd_gradient_7c(θ)               # 2*7 = 14 solves
        l = timing_loss_7c_f64(θ)           # 1 solve
        n_solve += solves_per_iter
        if l < best_loss; best_loss = l; best_x = copy(θ); end
        push!(losses, best_loss); push!(times, time()-t0); push!(solves, n_solve)
        adam_step_vec!(θ, g, m, v, iter; lr=lr)
    end
    return MethodResult7C("FD+ADAM", best_x, best_loss, losses, times, solves,
                          n_solve, time()-t0)
end

