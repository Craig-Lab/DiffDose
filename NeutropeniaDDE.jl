# ── Solve ANC trajectory (7-cycle) ────────────────────────
function solve_anc_7c(x_inj::Vector{Float64}; gcsf_flag=1)
    p = default_parameters(Float64)
    p.AdminChemo=1; p.AdminGCSF=gcsf_flag; p.DayAdminChemo=0.0; p.DeltaC=CHEMO_W
    p.Period=CYCLE_LEN; p.NumAdminsChemo=N_CYCLES; p.DoseChemo=4000.0
    p.TotalDose=4000.0*p.BSA; p.Dose=DOSE_AMT
    recompute_derived!(p)
    tspan = (0.0, T_END)
    cs = [ChemoInfusion(Float64(c*CYCLE_LEN), p.TotalDose, p.DeltaC) for c in 0:N_CYCLES-1]
    gs = if gcsf_flag == 0
        GCSFInjection{Float64,Float64}[]
    else
        [GCSFInjection(Float64(c*CYCLE_LEN) + x_inj[c+1], DOSE_AMT) for c in 0:N_CYCLES-1]
    end
    sol = solve_scenario_undeclared(p, tspan;
        chemo_schedule=cs, gcsf_schedule=gs,
        smooth_chemo=true,  chemo_smooth_shape=:sigmoid, chemo_smooth_width=SIGMOID_EPS,
        smooth_gcsf=(gcsf_flag==1), gcsf_smooth_shape=:sigmoid, gcsf_smooth_width=SIGMOID_EPS,
        reltol=1e-8, abstol=1e-8, dtmax=1e-2, saveat=SAVEAT)
    return sol.t, [ANC_SCALE * sol.u[i][ANC_IDX] for i in eachindex(sol.t)]
end

function solve_anc_7c_daily()
    p = default_parameters(Float64)
    p.AdminChemo=1; p.AdminGCSF=1; p.DayAdminChemo=0.0; p.DeltaC=CHEMO_W
    p.Period=CYCLE_LEN; p.NumAdminsChemo=N_CYCLES; p.DoseChemo=4000.0
    p.TotalDose=4000.0*p.BSA; p.Dose=DOSE_AMT
    recompute_derived!(p)
    tspan = (0.0, T_END)
    cs = [ChemoInfusion(Float64(c*CYCLE_LEN), p.TotalDose, p.DeltaC) for c in 0:N_CYCLES-1]
    # Daily G-CSF: days 1–13 of each cycle
    gs = GCSFInjection{Float64,Float64}[]
    for c in 0:N_CYCLES-1
        for k in 0:12
            push!(gs, GCSFInjection(Float64(c*CYCLE_LEN) + 1.0 + k, DOSE_AMT))
        end
    end
    sol = solve_scenario_undeclared(p, tspan;
        chemo_schedule=cs, gcsf_schedule=gs,
        smooth_chemo=true,  chemo_smooth_shape=:sigmoid, chemo_smooth_width=SIGMOID_EPS,
        smooth_gcsf=true,   gcsf_smooth_shape=:sigmoid,  gcsf_smooth_width=SIGMOID_EPS,
        reltol=1e-8, abstol=1e-8, dtmax=1e-2, saveat=SAVEAT)
    return sol.t, [ANC_SCALE * sol.u[i][ANC_IDX] for i in eachindex(sol.t)]
end

# ── Deficit helper ─────────────────────────────────────────
function compute_deficit_7c(t, anc)
    loss = 0.0
    for i in 2:length(t)
        dt = t[i]-t[i-1]
        a1 = anc[i-1]; a2 = anc[i]
        loss += 0.5*(max(0.0, ANC_THR-a1) + max(0.0, ANC_THR-a2))*dt
    end
    return loss
end

# ── Main benchmark ─────────────────────────────────────────
function main(args=ARGS)
    Random.seed!(42)

    options = parse_cli(args)
    preset = options["preset"]
    methods = options["methods"]
    results_dir = abspath(options["output"])
    mkpath(results_dir)
    budget = preset == "quick" ? 20 : 600

    println("="^70)
    println("  6-Method Benchmark  —  G-CSF Timing  ($(N_CYCLES) cycles CHOP-14)")
    println("  Dimension: $(DIM)  (one injection time per cycle)")
    println("  Loss = ∫₀⁹⁸ max(0, 2.0 − ANC) dt   [ANC·days below grade 3/4]")
    println("  Initial: day $(T_INIT) every cycle, 300 μg G-CSF")
    println("  Preset: $(preset); methods: $(methods)")
    println("  Budget: $(budget) forward DDE solves per method")
    println("  AD+ADAM  → $(budget÷2) iters @ 2 solves/iter")
    println("  FD+ADAM  → $(budget÷(2*DIM+1)) iters @ $(2*DIM+1) solves/iter")
    println("="^70)

    # ── Warm-up (JIT) ─────────────────────────────────────
    print("  Warming up JIT (7-cycle DDE)... ")
    x0 = fill(T_INIT, DIM)
    timing_loss_7c(x0)
    ad_gradient_7c(x0)
    println("done\n")

    # ── Run all 6 methods ─────────────────────────────────
    runners = [
        ("AD + ADAM", () -> run_ad_adam_7c(budget=budget, lr=0.05)),
        ("AD + L-BFGS", () -> run_ad_lbfgs_7c(budget=budget)),
    ]
    if methods == "all"
        append!(runners, [
            ("FD + ADAM", () -> run_fd_adam_7c(budget=budget, lr=0.05)),
            ("FD + L-BFGS", () -> run_fd_lbfgs_7c(budget=budget)),
            ("Nelder-Mead", () -> run_nelder_mead_7c(budget=budget)),
            ("Simulated Annealing", () -> run_sim_anneal_7c(budget=budget)),
        ])
    end
    results = MethodResult7C[]
    for (i, (label, runner)) in enumerate(runners)
        @printf("  [%d/%d] %s...\n", i, length(runners), label)
        r = runner()
        push!(results, r)
        days_str = join([@sprintf("%.1f", d) for d in r.best_x], ", ")
        @printf("         loss=%.4f  days=[%s]  (%d solves, %.1fs)\n",
                r.best_loss, days_str, r.total_solves, r.wall_time)
    end

    # ── Summary table ─────────────────────────────────────
    println("\n", "="^70)
    println("  Summary")
    println("="^70)
    @printf("  %-16s  %10s  %8s  %10s  %s\n",
            "Method", "Best Loss", "Solves", "Time (s)", "Best Days")
    println("  ", "-"^72)
    for r in results
        days_str = join([@sprintf("%.1f", d) for d in r.best_x], ", ")
        @printf("  %-16s  %10.4f  %8d  %10.2f  [%s]\n",
                r.name, r.best_loss, r.total_solves, r.wall_time, days_str)
    end

    # ── Reference scenarios ───────────────────────────────
    x_none   = fill(0.0, DIM)
    x_day4   = fill(T_INIT, DIM)
    x_day8   = fill(8.0, DIM)

    t_no, anc_no       = solve_anc_7c(x_none; gcsf_flag=0)
    loss_none          = compute_deficit_7c(t_no, anc_no)
    loss_day4          = timing_loss_7c_f64(x_day4)
    loss_day8          = timing_loss_7c_f64(x_day8)
    t_daily, anc_daily = solve_anc_7c_daily()
    loss_daily         = compute_deficit_7c(t_daily, anc_daily)

    # Best AD result
    ad_results = filter(r -> startswith(r.name, "AD"), results)
    best_ad = sort(ad_results, by=r -> r.best_loss)[1]
    x_opt = best_ad.best_x; loss_opt = best_ad.best_loss

    @printf("\n  References (7-cycle):\n")
    @printf("    no-GCSF     = %.4f\n", loss_none)
    @printf("    day-4 (init)= %.4f\n", loss_day4)
    @printf("    day-8 every = %.4f\n", loss_day8)
    @printf("    daily       = %.4f\n", loss_daily)
    opt_days_str = join([@sprintf("%.1f", d) for d in x_opt], ", ")
    @printf("    AD-opt      = %.4f  days=[%s]\n", loss_opt, opt_days_str)

    # ═════════════════════════════════════════════════════════
    #  SAVE CONVERGENCE HISTORY CSV
    # ═════════════════════════════════════════════════════════
    println("\n  Saving CSVs...")

    rows = NamedTuple[]
    for r in results
        for j in eachindex(r.loss_history)
            push!(rows, (method=r.name, step=j,
                         solves=r.solve_history[j],
                         wall_s=round(r.time_history[j]; digits=4),
                         best_loss=round(r.loss_history[j]; digits=6)))
        end
    end
    conv_path = joinpath(results_dir, "NeutropeniaDDE_convergence.csv")
    CSV.write(conv_path, DataFrame(rows))
    println("    ", conv_path)

    # Summary table
    summary_rows = [(method=r.name, best_loss=r.best_loss,
                     best_days=join([@sprintf("%.2f", d) for d in r.best_x], ";"),
                     total_solves=r.total_solves, wall_s=r.wall_time)
                    for r in results]
    summ_path = joinpath(results_dir, "NeutropeniaDDE_summary.csv")
    CSV.write(summ_path, DataFrame(summary_rows))
    println("    ", summ_path)

    # ANC trajectories for plotting
    scenarios = [
        ("no_gcsf",    x_none,  t_no,    anc_no,    loss_none),
        ("day8_every", x_day8,  solve_anc_7c(x_day8)..., loss_day8),
